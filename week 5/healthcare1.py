import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.read_csv("/content/drive/MyDrive/Python Programs/healthcare_dataset.csv")
df

print(df.head())

df.info()

df['Admission_Date'] = pd.to_datetime(df['Admission_Date'], format='%d-%m-%Y')
df['Discharge_Date'] = pd.to_datetime(df['Discharge_Date'], format='%d-%m-%Y')

print(df.isnull().sum())

df = df.dropna()

df = df.drop_duplicates()
df

df['Admission_Type'] = df['Admission_Type'].str.strip().str.title()
df['Admission_Category'] = df['Admission_Type'].replace({'Routine': 'Elective'})
admission_category_counts = df['Admission_Category'].value_counts()
print(admission_category_counts)

df["Hospital_Stays"] = (df["Discharge_Date"] - df["Admission_Date"]).dt.days
Hospital_Stays_Summary = df['Hospital_Stays'].describe()
print(Hospital_Stays_Summary)

Billing_Amount_Summary = df['Billing_Amount'].describe()
print(Billing_Amount_Summary)

medical_condition_counts = df['Medical_Condition'].value_counts()
print(medical_condition_counts)

medical_condition_gender_crosstab = pd.crosstab(df['Medical_Condition'], df['Gender'])
print(medical_condition_gender_crosstab)

medical_condition_age_summary = df.groupby('Medical_Condition')['Age'].mean()
print(medical_condition_age_summary)